#!/usr/bin/env bash
# Assemble a bootable, LUKS2-encrypted, Secure-Boot (signed-UKI) jaaOS disk image
# from out/rootfs.tar. Needs root (loop devices, cryptsetup, mount, chroot).
#
#   sudo build/mkimage.sh
#
# Env overrides:
#   IMG_SIZE=12G            image size
#   LUKS_PASSPHRASE=jaa demo FDE passphrase (CHANGE for anything real)
#   CMDLINE=kernel/cmdline  which kernel cmdline to bake into the UKI
set -euo pipefail

[ "$(id -u)" -eq 0 ] || { echo "Run as root: sudo $0" >&2; exit 1; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/out"
ROOTFS_TAR="$OUT/rootfs.tar"
IMG="$OUT/jaaos-minimal.img"
KEYS="$ROOT/build/secureboot/keys"
CMDLINE_FILE="${CMDLINE:-$ROOT/kernel/cmdline}"
IMG_SIZE="${IMG_SIZE:-12G}"
LUKS_PASSPHRASE="${LUKS_PASSPHRASE:-jaa}"
MAPPER="jaa_root"
MOUNTOPTS="compress=zstd:1,noatime,space_cache=v2"

[ -f "$ROOTFS_TAR" ]  || { echo "Missing $ROOTFS_TAR — run build/mkrootfs.sh first." >&2; exit 1; }
[ -f "$KEYS/db.key" ] || { echo "Missing Secure Boot keys — run build/secureboot.sh first." >&2; exit 1; }
for t in sgdisk cryptsetup mkfs.btrfs btrfs mkfs.vfat losetup blkid; do
	command -v "$t" >/dev/null 2>&1 || { echo "Missing host tool: $t" >&2; exit 1; }
done

WORK="$(mktemp -d)"
MNT="$WORK/mnt"; mkdir -p "$MNT"
LOOP=""
cleanup() {
	set +e
	mountpoint -q "$MNT/run"      && umount -l "$MNT/run"
	mountpoint -q "$MNT/sys"      && umount -l "$MNT/sys"
	mountpoint -q "$MNT/proc"     && umount -l "$MNT/proc"
	mountpoint -q "$MNT/dev/pts"  && umount -l "$MNT/dev/pts"
	mountpoint -q "$MNT/dev"      && umount -l "$MNT/dev"
	mountpoint -q "$MNT/boot/efi" && umount "$MNT/boot/efi"
	mountpoint -q "$MNT"          && umount -R "$MNT"
	[ -e "/dev/mapper/$MAPPER" ]  && cryptsetup close "$MAPPER"
	[ -n "$LOOP" ] && losetup -d "$LOOP"
	rm -rf "$WORK"
}
trap cleanup EXIT

echo "==> Creating ${IMG_SIZE} image"
rm -f "$IMG"
truncate -s "$IMG_SIZE" "$IMG"

echo "==> Partitioning (GPT: ESP + LUKS)"
sgdisk --zap-all "$IMG" >/dev/null
sgdisk -n1:0:+512M -t1:ef00 -c1:ESP "$IMG" >/dev/null
sgdisk -n2:0:0     -t2:8309 -c2:jaa_luks "$IMG" >/dev/null   # 8309 = Linux LUKS

LOOP="$(losetup -fP --show "$IMG")"
ESP_DEV="${LOOP}p1"
LUKS_DEV="${LOOP}p2"

echo "==> Formatting ESP"
mkfs.vfat -F32 -n ESP "$ESP_DEV" >/dev/null

echo "==> LUKS2 (Argon2id) on $LUKS_DEV"
printf '%s' "$LUKS_PASSPHRASE" | cryptsetup luksFormat --type luks2 \
	--pbkdf argon2id --pbkdf-memory 1048576 --pbkdf-parallel 4 \
	--cipher aes-xts-plain64 --key-size 512 --hash sha512 \
	--batch-mode "$LUKS_DEV" -
printf '%s' "$LUKS_PASSPHRASE" | cryptsetup open "$LUKS_DEV" "$MAPPER" -

echo "==> Btrfs + subvolumes"
mkfs.btrfs -L jaa -f "/dev/mapper/$MAPPER" >/dev/null
mount "/dev/mapper/$MAPPER" "$MNT"
for sv in @ @home @snapshots @var @log; do
	btrfs subvolume create "$MNT/$sv" >/dev/null
done
umount "$MNT"

mount -o "subvol=@,$MOUNTOPTS" "/dev/mapper/$MAPPER" "$MNT"
mkdir -p "$MNT"/{home,.snapshots,var,boot/efi}
mount -o "subvol=@home,$MOUNTOPTS"      "/dev/mapper/$MAPPER" "$MNT/home"
mount -o "subvol=@snapshots,$MOUNTOPTS" "/dev/mapper/$MAPPER" "$MNT/.snapshots"
mount -o "subvol=@var,$MOUNTOPTS"       "/dev/mapper/$MAPPER" "$MNT/var"
mkdir -p "$MNT/var/log"
mount -o "subvol=@log,$MOUNTOPTS"       "/dev/mapper/$MAPPER" "$MNT/var/log"
mount "$ESP_DEV" "$MNT/boot/efi"

echo "==> Unpacking rootfs"
tar -C "$MNT" -xpf "$ROOTFS_TAR" --xattrs-include='*' --numeric-owner

LUKS_UUID="$(blkid -s UUID -o value "$LUKS_DEV")"
ESP_UUID="$(blkid -s UUID -o value "$ESP_DEV")"

echo "==> crypttab / fstab / cmdline"
cat > "$MNT/etc/crypttab" <<EOF
# <name>        <device>              <keyfile> <options>
$MAPPER UUID=$LUKS_UUID none luks,discard
EOF

cat > "$MNT/etc/fstab" <<EOF
# jaaOS fstab (generated by mkimage.sh)
/dev/mapper/$MAPPER /           btrfs subvol=@,$MOUNTOPTS 0 0
/dev/mapper/$MAPPER /home       btrfs subvol=@home,$MOUNTOPTS 0 0
/dev/mapper/$MAPPER /.snapshots btrfs subvol=@snapshots,$MOUNTOPTS 0 0
/dev/mapper/$MAPPER /var        btrfs subvol=@var,$MOUNTOPTS 0 0
/dev/mapper/$MAPPER /var/log    btrfs subvol=@log,$MOUNTOPTS 0 0
UUID=$ESP_UUID /boot/efi vfat umask=0077,shortname=winnt 0 2
tmpfs /tmp     tmpfs rw,nosuid,nodev,noexec,size=2G 0 0
tmpfs /var/tmp tmpfs rw,nosuid,nodev,noexec,size=1G 0 0
EOF

# Bake the kernel command line into /etc/kernel/cmdline (ukify reads it); strip comments.
install -d "$MNT/etc/kernel"
grep -vE '^[[:space:]]*#' "$CMDLINE_FILE" | tr -d '\n' | sed 's/[[:space:]]\+/ /g; s/^ //; s/ $//' \
	> "$MNT/etc/kernel/cmdline"
echo "" >> "$MNT/etc/kernel/cmdline"

echo "==> Entering chroot for initramfs, bootloader, UKI, snapper"
mount --bind /dev     "$MNT/dev"
mount --bind /dev/pts "$MNT/dev/pts"
mount -t proc  proc   "$MNT/proc"
mount -t sysfs sysfs  "$MNT/sys"
mount -t tmpfs tmpfs  "$MNT/run"
# Private keys go on the tmpfs /run (vanish when it is unmounted — never in the image).
mkdir -p "$MNT/run/keys"
cp "$KEYS/db.key" "$KEYS/db.crt" "$MNT/run/keys/"

chroot "$MNT" /usr/bin/env -i \
	PATH=/usr/sbin:/usr/bin:/sbin:/bin HOME=/root DEBIAN_FRONTEND=noninteractive \
	/bin/bash -euo pipefail <<'CHROOT'
KVER="$(ls -1 /boot/vmlinuz-* | sort -V | tail -n1)"; KVER="${KVER#/boot/vmlinuz-}"
echo "    kernel: $KVER"

# initramfs now sees /etc/crypttab -> cryptsetup-initramfs bakes in the unlock config
update-initramfs -u -k "$KVER"

# systemd-boot onto the ESP (no NVRAM writes inside a chroot)
bootctl install --esp-path=/boot/efi --no-variables

cat > /boot/efi/loader/loader.conf <<EOF
default jaaos-*.efi
timeout 3
console-mode auto
editor no
EOF

# Build + sign the Unified Kernel Image (kernel + initrd + cmdline, as one signed PE)
mkdir -p /boot/efi/EFI/Linux
ukify build \
	--linux="/boot/vmlinuz-$KVER" \
	--initrd="/boot/initrd.img-$KVER" \
	--cmdline=@/etc/kernel/cmdline \
	--os-release=@/etc/os-release \
	--signtool=sbsign \
	--secureboot-private-key=/run/keys/db.key \
	--secureboot-certificate=/run/keys/db.crt \
	--output="/boot/efi/EFI/Linux/jaaos-$KVER.efi"

# Sign the systemd-boot binaries too (both the normal and removable paths)
for f in /boot/efi/EFI/systemd/systemd-bootx64.efi /boot/efi/EFI/BOOT/BOOTX64.EFI; do
	[ -f "$f" ] && sbsign --key /run/keys/db.key --cert /run/keys/db.crt --output "$f" "$f"
done

# snapper config for / (the @snapshots subvol is already mounted at /.snapshots)
install -Dm644 /usr/share/snapper/config-templates/default /etc/snapper/configs/root
sed -i 's#^SUBVOLUME=.*#SUBVOLUME="/"#'            /etc/snapper/configs/root
sed -i 's#^TIMELINE_CREATE=.*#TIMELINE_CREATE="no"#' /etc/snapper/configs/root
printf 'SNAPPER_CONFIGS="root"\n' > /etc/default/snapper

# Clean the apt lists so the image is smaller and reproducible-ish
apt-get clean || true
rm -f /run/keys/db.key /run/keys/db.crt
echo "    chroot steps done"
CHROOT

echo "==> Done: $IMG"
sync
echo "Verify signatures with: sbverify --list \"$IMG\" (after mapping) or boot the VM test."
